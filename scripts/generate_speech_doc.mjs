function p(text, options = {}) {
  return new Paragraph({
    alignment: options.alignment || AlignmentType.JUSTIFIED,
    indent: options.noIndent ? undefined : { firstLine: 709 },
    spacing: { line: 360, after: options.after !== undefined ? options.after : 120, before: options.before || 0 },
    children: [
      new TextRun({
        text: text,
        font: 'Times New Roman',
        size: options.size || 28, // 14pt
        bold: options.bold || false,
        italics: options.italics || false,
      })
    ]
  });
}

function h1(title) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 360, after: 240 },
    children: [
      new TextRun({
        text: title,
        font: 'Times New Roman',
        size: 32,
        bold: true,
      })
    ]
  });
}

function h2(title) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { firstLine: 709 },
    spacing: { before: 240, after: 140 },
    children: [
      new TextRun({
        text: title,
        font: 'Times New Roman',
        size: 28,
        bold: true,
      })
    ]
  });
}

function metaP(label, val) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { firstLine: 709 },
    spacing: { line: 300, after: 80 },
    children: [
      new TextRun({ text: label + ': ', font: 'Times New Roman', size: 26, bold: true, color: 'b45309' }),
      new TextRun({ text: val, font: 'Times New Roman', size: 26, italics: true, color: '1e293b' })
    ]
  });
}

function speechP(text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: 709 },
    spacing: { line: 360, after: 140 },
    children: [
      new TextRun({ text: '«' + text + '»', font: 'Times New Roman', size: 28, color: '0f172a' })
    ]
  });
}

